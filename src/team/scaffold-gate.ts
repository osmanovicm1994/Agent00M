// src/team/scaffold-gate.ts
//
// "The app still looks like the default Next.js page." A scaffold command writes a starter home page; a team run that built
// an application on top of it but never replaced that page has delivered something the person opens and sees "To get started,
// edit the page.tsx file". Every task can report "done" and the result is still not what was asked for.
//
// This gate looks at the files on disk (no model call) and says whether a generated starter page or starter title is still in
// place. Team mode uses it once, after all tasks: one repair run by the frontend engineer when everything else is done, and an
// honest "not complete" in the report when it still stands.
//
// Pure file reading, no writes.

import * as fs from "fs";
import * as path from "path";

export interface ScaffoldFinding {
  /** Path relative to the workspace, forward slashes. */
  file: string;
  /** What is still the generated default. */
  why: string;
  /** The starter PAGE must be replaced. A default page title alone is only reported. */
  blocking: boolean;
}

// Text of the pages create-next-app writes (Next 13 to 16). Any one of these in a home page means it was never replaced.
const STARTER_PAGE_MARKERS: RegExp[] = [
  /To get started, edit the page\.tsx file/i,
  /Looking for a starting point or more instructions/i,
  /Get started by editing/i,
  /Save and see your changes instantly/i,
];

const SKIP_DIRS = new Set(["node_modules", ".next", "dist", "build", ".git", "tasks", "coverage"]);
const PAGE_EXTS = ["tsx", "jsx", "ts", "js"];

function readSmall(file: string): string {
  try {
    return fs.readFileSync(file, "utf8").slice(0, 40_000);
  } catch {
    return "";
  }
}

function subdirs(dir: string): string[] {
  try {
    return fs
      .readdirSync(dir, { withFileTypes: true })
      .filter((e) => e.isDirectory() && !e.name.startsWith(".") && !SKIP_DIRS.has(e.name))
      .map((e) => path.join(dir, e.name));
  } catch {
    return [];
  }
}

function usesNext(dir: string): boolean {
  try {
    const pkg = JSON.parse(readSmall(path.join(dir, "package.json")));
    return Boolean({ ...pkg.dependencies, ...pkg.devDependencies }.next);
  } catch {
    return false;
  }
}

/** Folders that may hold a Next.js app: the workspace, its subfolders, and apps/* and packages/*. */
export function candidateAppDirs(root: string): string[] {
  const dirs = new Set<string>([root]);
  const top = subdirs(root);
  top.forEach((d) => dirs.add(d));
  for (const container of ["apps", "packages"]) subdirs(path.join(root, container)).forEach((d) => dirs.add(d));
  return [...dirs].slice(0, 80);
}

export function isStarterPage(text: string): boolean {
  if (STARTER_PAGE_MARKERS.some((re) => re.test(text))) return true;
  // The older starter: the vercel/next logo image plus the two buttons.
  return /(?:next|vercel)\.svg/.test(text) && /Deploy now/i.test(text) && /(Read our docs|Documentation)/i.test(text);
}

export function hasStarterMetadata(text: string): boolean {
  return /title:\s*["']Create Next App["']/.test(text) || /Generated by create next app/i.test(text);
}

/** Generated starter content that is still in place in every Next.js app found under the workspace. */
export function findStarterContent(root: string): ScaffoldFinding[] {
  const out: ScaffoldFinding[] = [];
  const rel = (f: string) => path.relative(root, f).split(path.sep).join("/");

  for (const dir of candidateAppDirs(root)) {
    if (!usesNext(dir)) continue;
    for (const base of ["src/app", "app"]) {
      for (const ext of PAGE_EXTS) {
        const page = path.join(dir, base, `page.${ext}`);
        if (fs.existsSync(page) && isStarterPage(readSmall(page))) {
          out.push({ file: rel(page), why: "the home page is still the page create-next-app generated", blocking: true });
        }
        const layout = path.join(dir, base, `layout.${ext}`);
        if (fs.existsSync(layout) && hasStarterMetadata(readSmall(layout))) {
          out.push({ file: rel(layout), why: 'the title or description is still the generated "Create Next App"', blocking: false });
        }
      }
    }
  }
  return out;
}

/** One line per finding, for logs and for the report facts. */
export function describeStarter(findings: readonly ScaffoldFinding[]): string {
  return findings.map((f) => `${f.file}: ${f.why}`).join("; ");
}

/** The task given to the frontend engineer for the one repair run. */
export function starterFixTask(findings: readonly ScaffoldFinding[]): string {
  return [
    "The generated Next.js starter content is still in place, so the app opens on the default page instead of the product:",
    ...findings.map((f) => `- ${f.file}: ${f.why}`),
    "",
    "Replace it now:",
    "1. Read the request and the notes of the earlier tasks (in this prompt), then read the layout and the existing pages and routes.",
    "2. Write the real home page (src/app/page.tsx). If the product has accounts, send a visitor to the login page and a signed-in user to the main screen. Read the session on the server for that, and keep any data read inside <Suspense> if the project uses cacheComponents.",
    "3. Set the real title and description in layout.tsx, and the page language.",
    "4. Any route the request names that has no page yet gets a real page now, not a placeholder.",
    "5. Run the typecheck and the build. Report the exact result.",
  ].join("\n");
}
